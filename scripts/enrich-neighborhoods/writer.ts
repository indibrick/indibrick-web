// Merges enrichment results into a resumable staging TS file. Each entry
// includes the source URLs + confidence + notes as inline comments so the
// human reviewer can decide whether to promote the entry into the real
// data/neighborhoodExtras.ts file.

import * as fs from 'fs';
import * as path from 'path';
import { CONFIG } from './config';
import type { EnrichmentResult } from './types';

const HEADER = `// AUTO-GENERATED by scripts/enrich-neighborhoods.
//
// Each entry below is a proposed update to data/neighborhoodExtras.ts.
// Every field is grounded in the sources listed in the // SOURCES comment
// (Wikipedia, OpenStreetMap, walkscore.com) — the LLM structuring step is
// prompted to REFUSE to fill in from training data.
//
// Workflow:
//   1. Read each entry. Sanity-check high-confidence ones (they're usually
//      correct — Wikipedia + OSM don't lie about what's on the ground).
//   2. Copy/paste entries you trust into data/neighborhoodExtras.ts,
//      MERGING with the existing keys there (this file only carries the
//      fields the pipeline found — merge with the existing
//      architecturalEra/historyBlurb/buyerProfile from the source file).
//   3. Skip or manually correct low-confidence entries.
//
// Re-running the pipeline is idempotent — entries already in this staging
// file will be skipped.

/* eslint-disable */
export const ENRICHED: Record<string, any> = {
`;

const FOOTER = `};
`;

export function loadStaging(): Set<string> {
  const p = path.resolve(CONFIG.stagingPath);
  if (!fs.existsSync(p)) return new Set();
  const text = fs.readFileSync(p, 'utf8');
  const keys = new Set<string>();
  const re = /'([a-z0-9-]+\|[a-z0-9-]+)':\s*\{/g;
  let m;
  while ((m = re.exec(text)) !== null) keys.add(m[1]);
  return keys;
}

// Overwrites the staging file. We assemble the full content each write
// (rather than in-place patch) because it's simpler and 260 entries is
// cheap. Called after each successful research to make the process
// resumable — network hiccup halfway through and you don't lose work.
export function writeStaging(all: EnrichmentResult[]) {
  const p = path.resolve(CONFIG.stagingPath);
  fs.mkdirSync(path.dirname(p), { recursive: true });

  const body = all
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((r) => renderEntry(r))
    .join('\n\n');

  fs.writeFileSync(p, HEADER + body + '\n' + FOOTER);
}

function renderEntry(r: EnrichmentResult): string {
  const sourceLine = r.sources.length
    ? `  // SOURCES: ${r.sources.join(' | ')}\n`
    : `  // SOURCES: (none — pipeline had no external data)\n`;
  const confLine = `  // CONFIDENCE: ${r.confidence}\n`;
  const notesLine = r.notes.length ? `  // NOTES: ${r.notes.join(' | ')}\n` : '';

  const fields = renderUpdate(r.update);
  return `${sourceLine}${confLine}${notesLine}  '${r.key}': ${fields},`;
}

function renderUpdate(u: Record<string, any>): string {
  if (Object.keys(u).length === 0) return `{ /* pipeline produced no additions — leave as standard-tier */ }`;
  return JSON.stringify(u, null, 2)
    .split('\n')
    .map((line, i) => (i === 0 ? line : '  ' + line))
    .join('\n');
}
